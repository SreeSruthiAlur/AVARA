from pydantic import BaseModel, Field
from typing import Optional, List, Dict, Any
from datetime import datetime, date

# -------------------------------------------------------------
# TEAMMATE 1 INTEGRATION CONTRACT: ASTROLOGY MODULE
# -------------------------------------------------------------
class AstrologyBirthChartRequest(BaseModel):
    user_id: int
    birth_date: str = Field(..., description="Date of birth in YYYY-MM-DD")
    birth_time: str = Field(..., description="Time of birth in HH:MM")
    birth_place: str = Field(..., description="City, State, Country coordinates or name")
    preferred_language: str = "te"

class PlanetPosition(BaseModel):
    planet: str
    sign: str
    degree: float
    house: int
    is_retrograde: bool = False

class AstrologyResponse(BaseModel):
    status: str = Field(..., description="'ready', 'pending', or 'mock_adapter'")
    provider_module: str = "teammate_1_astrology"
    chart_calculated: bool = False
    sun_sign: Optional[str] = None
    moon_sign: Optional[str] = None
    ascendant: Optional[str] = None
    planetary_positions: List[PlanetPosition] = []
    interpretation_summary: str = Field(
        ...,
        description="Astrological interpretation to be generated by Teammate 1"
    )
    evidence_notes: Optional[str] = Field(
        None,
        description="Astrological evidence/scriptural citations by Teammate 1"
    )
    disclaimer: str = "Astrological insights are for personal guidance and not deterministic guarantees."

# -------------------------------------------------------------
# TEAMMATE 1 INTEGRATION CONTRACT: HABITS MODULE
# -------------------------------------------------------------
class HabitContractItem(BaseModel):
    id: Optional[int] = None
    title: str
    frequency: str  # "daily", "weekly"
    target_days_per_week: int = 7
    current_streak: int = 0
    is_completed_today: bool = False

class HabitsSummaryResponse(BaseModel):
    status: str = Field(..., description="'ready', 'pending', or 'mock_adapter'")
    provider_module: str = "teammate_1_habits"
    total_active_habits: int = 0
    habits: List[HabitContractItem] = []
    completion_rate_pct: float = 0.0
    consistency_score: float = 0.0
    message: str = "Habits module interface provided by Teammate 2. Business logic to be hooked by Teammate 1."

# -------------------------------------------------------------
# TEAMMATE 1 INTEGRATION CONTRACT: INSIGHTS MODULE
# -------------------------------------------------------------
class InsightObservation(BaseModel):
    category: str  # "wellness", "discipline", "routine", "astrology_link"
    title: str
    observation: str
    confidence: float

class InsightsSummaryResponse(BaseModel):
    status: str = Field(..., description="'ready', 'pending', or 'mock_adapter'")
    provider_module: str = "teammate_1_insights"
    reflection_summary: str
    key_observations: List[InsightObservation] = []
    practical_suggestions: List[str] = []
    message: str = "Insights module interface provided by Teammate 2. Synthesis engine to be hooked by Teammate 1."
